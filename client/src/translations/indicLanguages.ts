type DeepPartial<T> = {
  [P in keyof T]?: T[P] extends object ? DeepPartial<T[P]> : T[P];
};

export function createIndicTranslation(
  base: TranslationStructure,
  overrides: DeepPartial<TranslationStructure>
): TranslationStructure {
  const result = JSON.parse(JSON.stringify(base)) as TranslationStructure;
  for (const [secKey, secVal] of Object.entries(overrides)) {
    if (secVal && typeof secVal === 'object') {
      for (const [k, v] of Object.entries(secVal)) {
        if (v !== undefined) {
          (result as any)[secKey][k] = v;
        }
      }
    }
  }
  return result;
}

